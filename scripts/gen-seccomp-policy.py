# Writes src/seccomp_policy.rs: the system calls the file-only tier may make, with their x86_64 numbers.
#   uv run scripts/gen-seccomp-policy.py docker-default.json > src/seccomp_policy.rs
# The base is the unconditional allowlist of Docker's default profile (moby/profiles, seccomp/default.json), which is the most
# reviewed list there is. This tier runs fixed utilities over files, so it is cut further: no namespaces, no sockets, no tracing, no
# in-memory executables, no LDT. clone stays, without namespace flags, and is handled in src/seccomp.rs.
import json, re, sys

profile = json.load(open(sys.argv[1]))
header = open("/usr/include/x86_64-linux-gnu/asm/unistd_64.h").read()
nr = {m[0]: int(m[1]) for m in re.findall(r"#define __NR_(\w+) (\d+)", header)}
drop = {"memfd_create", "memfd_secret", "modify_ldt", "clone", "clone3"}
names = sorted(({*profile["syscalls"][0]["names"], "arch_prctl"}) - drop)
allowed = [n for n in names if n in nr]
missing = [n for n in names if n not in nr]   # names for other architectures and newer kernels than the header
print(f"""// Generated by scripts/gen-seccomp-policy.py from Docker's default seccomp profile (moby/profiles 6fe7deb, 2026-09-17).
// Not for editing. {len(allowed)} system calls; left out because this header has no number for them: {", ".join(missing) or "none"}.
pub const ALLOWED: &[(&str, u32)] = &[""")
for n in allowed:
    print(f'    ("{n}", {nr[n]}),')
print(f"""];
pub const NR_CLONE: u32 = {nr["clone"]};
pub const NR_CLONE3: u32 = {nr["clone3"]};""")
