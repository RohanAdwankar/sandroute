// Writes src/seccomp-policy.ts: the system calls the file-only tier may make, with their x86_64 numbers.
//   node scripts/gen-seccomp-policy.mjs docker-default.json > src/seccomp-policy.ts
// The base is the unconditional allowlist of Docker's default profile (moby/profiles, seccomp/default.json),
// which is the most reviewed list there is. This tier runs fixed utilities over files, so it is cut further:
// no namespaces, no sockets, no tracing, no in-memory executables, no LDT. clone stays, without namespace
// flags, and is handled in src/seccomp.ts.
import { readFileSync } from "node:fs";

const profile = JSON.parse(readFileSync(process.argv[2], "utf8"));
const header = readFileSync("/usr/include/x86_64-linux-gnu/asm/unistd_64.h", "utf8");
const nr = Object.fromEntries([...header.matchAll(/#define __NR_(\w+) (\d+)/g)].map((m) => [m[1], Number(m[2])]));

const drop = new Set(["memfd_create", "memfd_secret", "modify_ldt", "clone", "clone3"]);
const names = [...new Set([...profile.syscalls[0].names, "arch_prctl"])].filter((n) => !drop.has(n)).sort();
const missing = names.filter((n) => !(n in nr));   // names for other architectures and newer kernels than the header
const allowed = names.filter((n) => n in nr);
console.log(`// Generated by scripts/gen-seccomp-policy.mjs from Docker's default seccomp profile (moby/profiles 6fe7deb, 2026-09-17).
// Not for editing. ${allowed.length} system calls; left out because this header has no number for them: ${missing.join(", ") || "none"}.
export const ALLOWED: Record<string, number> = {
${allowed.map((n) => `  ${n}: ${nr[n]},`).join("\n")}
};
export const NR = { clone: ${nr.clone}, clone3: ${nr.clone3} };`);
